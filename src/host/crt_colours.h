constexpr int N_PRESETS = int(sizeof PRESETS / sizeof PRESETS[0]);
// The player's settings: brightness and gamma in percent (100 as the game's), 50-150 and 50-200
constexpr int BRIGHT_MIN = 50, BRIGHT_MAX = 150, GAMMA_MIN = 50, GAMMA_MAX = 200;

class Colours
{
public:
	// Draws `tex` into the current target (dst null: all of it) through the colours, or plainly when they're all as
	// the game's or this renderer can't. False: drawn plainly.
	bool draw(SDL_Renderer *ren, SDL_Texture *tex, const SDL_FRect *dst, int preset_i, int bright, int gamma)
	{
		const bool plain = preset_i <= 0 && bright == 100 && gamma == 100;
		if (plain || !ready(ren)) { SDL_RenderTexture(ren, tex, nullptr, dst); return false; }
		if (preset_i != set_p || bright != set_b || gamma != set_g) {
			const preset &p = PRESETS[preset_i < N_PRESETS ? preset_i : 0];
			// brightness: the light scaled, as much as the picture looks that much brighter (sRGB's out is about the
			// 2.2th root); gamma: the exponent in divided by it (higher: the middle tones brighter)
			const float k = std::pow(bright / 100.0f, 2.2f), gm = gamma / 100.0f;
			float g = p.gamma;
			if (gamma != 100) g = (g > 0 ? g : 2.2f) / gm;   // (sRGB's curve kept while the gamma is the game's)
			const float u[12] = { k * p.m[0], k * p.m[1], k * p.m[2], g, k * p.m[3], k * p.m[4], k * p.m[5], 0, k * p.m[6], k * p.m[7], k * p.m[8], 0 };
			SDL_SetGPURenderStateFragmentUniforms(state, 0, u, sizeof u);
			set_p = preset_i; set_b = bright; set_g = gamma;
		}
		SDL_SetGPURenderState(ren, state);
		SDL_RenderTexture(ren, tex, nullptr, dst);
		SDL_SetGPURenderState(ren, nullptr);
		return true;
	}
	bool failed() const { return fail; }   // (not on this renderer: the menu says so)
	void lost() { state = nullptr; shader = nullptr; for_ren = nullptr; set_p = -1; }   // (the renderer's device reset, or a new renderer)
	void release()   // (before the renderer goes)
	{
		if (state) SDL_DestroyGPURenderState(state);
		if (shader && for_ren) if (SDL_GPUDevice *gd = SDL_GetGPURendererDevice(for_ren)) SDL_ReleaseGPUShader(gd, shader);
		lost();
	}

private:
	SDL_GPURenderState *state = nullptr;
	SDL_GPUShader *shader = nullptr;
	SDL_Renderer *for_ren = nullptr;
	bool fail = false;
	int set_p = -1, set_b = -1, set_g = -1;
	bool ready(SDL_Renderer *ren)
	{
		if (state && for_ren == ren) return true;
		if (for_ren != ren) { state = nullptr; shader = nullptr; fail = false; set_p = -1; }
		if (fail) return false;
		for_ren = ren;
		SDL_GPUDevice *gd = SDL_GetGPURendererDevice(ren);
		if (gd) {
			const SDL_GPUShaderFormat have = SDL_GetGPUShaderFormats(gd);
			SDL_GPUShaderCreateInfo ci = {};
			if (have & SDL_GPU_SHADERFORMAT_SPIRV) { ci.format = SDL_GPU_SHADERFORMAT_SPIRV; ci.code = crt_colour_spv; ci.code_size = sizeof(crt_colour_spv); }
			else if (have & SDL_GPU_SHADERFORMAT_DXIL) { ci.format = SDL_GPU_SHADERFORMAT_DXIL; ci.code = crt_colour_dxil; ci.code_size = sizeof(crt_colour_dxil); }
			else if (have & SDL_GPU_SHADERFORMAT_MSL) { ci.format = SDL_GPU_SHADERFORMAT_MSL; ci.code = crt_colour_msl; ci.code_size = sizeof(crt_colour_msl) - 1; }
			if (ci.code) {
				ci.entrypoint = ci.format == SDL_GPU_SHADERFORMAT_MSL ? "main0" : "main";
				ci.stage = SDL_GPU_SHADERSTAGE_FRAGMENT;
				ci.num_samplers = 1;
				ci.num_uniform_buffers = 1;
				shader = SDL_CreateGPUShader(gd, &ci);
			}
			SDL_GPURenderStateCreateInfo si = {};
			si.fragment_shader = shader;
			if (shader) state = SDL_CreateGPURenderState(ren, &si);
		}
		if (!state) {
			fprintf(stderr, "CRT colours, brightness and gamma: not on this renderer (%s)\n", gd ? SDL_GetError() : "SDL's GPU renderer only");
			fail = true;
			return false;
		}
		return true;
	}
};

